    [InlineData(323, 40, 20.5, false, "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAArgNX/////1YArAAAAAAAAK4DV///////VgCsAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA")]
    [InlineData(323, 49, 20.5, false, "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAK4DV////////1YArAAAAAAAAK4DV////1YArAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA")]
    [InlineData(323, 40, 20.5, true, "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAArgNX/////1YArAAAAAAAAK4DV///////VgCsAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA")]
    [InlineData(323, 40, -19.5, false, "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAArgNX/////1YArAAAAAAAAK4DV///////VgCsAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA")]
    [InlineData(323, 29, 20.5, true, "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAABVqv//1YArAAAAAAAAAFWq//////////+qVQAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA")]
    public void Natural_line_midpoints_preserve_native_crossing_quantization(int width, int shift, double originX, bool reverse, string rgb)
    {
        // Original CC0 nonparallel band: independently captured DirectWrite
        // RGB, UPEM 2048, em 32, gasp 7, SCANCTRL 511 / SCANTYPE 5.
        // Distinct slopes expose native dropout-crossing quantization. Other
        // phases isolate upper glyph bounds and an exact top vertex supported
        // by both scan directions, including reversed and signed placements.
        OpenTypeOutlinePoint a = P(0, shift), b = P(width, 67 + shift);
        OpenTypeOutlinePoint c = P(width, 43 + shift), d = P(0, shift - 25);
        OpenTypeQuadraticSegment[] segments = [new(a, b, b), new(b, c, c), new(c, d, d), new(d, a, a)];
        if (reverse)
            segments = segments.Reverse().Select(segment => new OpenTypeQuadraticSegment(segment.End, segment.Start, segment.Start)).ToArray();
        AssertNaturalRows(segments, false, true, (int)Math.Floor(originX) - 1, 76, 8, 6, Convert.FromBase64String(rgb));

        OpenTypeOutlinePoint P(int x, int y) => new(originX + x / 64d, 80 - y / 64d);
    }
    [Fact]
    public void Natural_steep_line_profiles_preserve_native_rounded_crossings()
    {
        // Original CC0 trapezoid, independent DirectWrite texture: em 32,
        // UPEM 2048, origin (20.75,80), SCANCTRL 511 / SCANTYPE 4.
        // A ceiling seed moves one cell to the wrong row on this steep edge.
        OpenTypeOutlinePoint[] points = [P(54, 112), P(170, 314), P(182, 293), P(76, 109)];
        OpenTypeQuadraticSegment[] segments = new OpenTypeQuadraticSegment[4];
        for (int index = 0; index < points.Length; index++)
        {
            OpenTypeOutlinePoint next = points[(index + 1) % points.Length];
            segments[index] = new(points[index], next, next);
        }
        AssertNaturalRows(segments, false, false, 19, 74, 8, 8, Convert.FromBase64String("AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAArgIBVAAAAAAAAAAAAAAAAAAAAAAAAAFWAgCsAAAAAAAAAAAAAAAAAAAAAAFWq/6pVAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"));

        static OpenTypeOutlinePoint P(int x, int y) => new(20 + 5d / 6 + x / 64d, 80 - y / 64d);
    }

}
