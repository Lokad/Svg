"""Regenerate pinned, default-language uppercase data; source downloads stay in RAM."""
from pathlib import Path
import hashlib
import json
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://www.unicode.org/Public/17.0.0/ucd/"
EXPECTED = {"UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
            "SpecialCasing.txt": "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588"}


def main():
    sources = {}
    for name in ["UnicodeData.txt", "SpecialCasing.txt"]:
        with urllib.request.urlopen(BASE + name, timeout=60) as response:
            payload = response.read(8 * 1024 * 1024)
        sources[name] = payload
        if hashlib.sha256(payload).hexdigest() != EXPECTED[name]:
            raise ValueError("Pinned Unicode input hash changed: " + name)
    mappings = {}
    for row in sources["UnicodeData.txt"].decode("utf-8").splitlines():
        fields = row.split(";")
        if fields[12]:
            mappings[int(fields[0], 16)] = (int(fields[12], 16),)
    for row in sources["SpecialCasing.txt"].decode("utf-8").splitlines():
        fields = row.split("#", 1)[0].strip().split(";")
        if len(fields) >= 5 and not fields[4].strip():
            mappings[int(fields[0], 16)] = tuple(int(x, 16) for x in fields[3].split())
    mappings = {key: value for key, value in sorted(mappings.items()) if value != (key,)}
    simple = [(key, value[0]) for key, value in mappings.items() if len(value) == 1]
    expansions = [(key, value) for key, value in mappings.items() if len(value) > 1]
    assert all(scalar <= 0xFFFF for _, value in expansions for scalar in value)
    assert max(len("".join(map(chr, value)).encode("utf-16-le")) // 2 for value in mappings.values()) == 3
    lines = ["// Generated by tools/generate-unicode-uppercase.py from Unicode 17.0.0.",
             "// Copyright Unicode, Inc. See THIRD_PARTY_NOTICES.txt (Unicode License V3).",
             "namespace Lokad.Svg.Parsing;", "", "internal static partial class SvgTextCasing", "{",
             "    private static ReadOnlySpan<int> UppercasePairs =>", "    ["]
    for offset in range(0, len(simple), 5):
        lines.append("        " + ", ".join(f"0x{key:X}, 0x{value:X}" for key, value in simple[offset:offset + 5]) + ",")
    lines += ["    ];", "", "    private static ReadOnlySpan<int> UppercaseExpansionRows =>", "    ["]
    offset = 0
    all_units = []
    for key, value in expansions:
        units = "".join(f"\\u{x:04X}" for x in value)
        lines.append(f"        0x{key:X}, {offset}, {len(value)},")
        offset += len(value)
        all_units.append(units)
    lines += ["    ];", "", "    private static ReadOnlySpan<char> UppercaseExpansionText =>"]
    for index in range(0, len(all_units), 5):
        end = ";" if index + 5 >= len(all_units) else " +"
        lines.append('        "' + "".join(all_units[index:index + 5]) + '"' + end)
    lines += ["}", ""]
    (ROOT / "src/Lokad.Svg/Parsing/SvgTextCasing.Data.cs").write_bytes("\n".join(lines).encode("utf-8"))
    bank = ROOT / "tests/Research/text-case-mapping"
    bank.mkdir(exist_ok=True)
    (bank / "unicode-uppercase.csv").write_bytes(("source;uppercase\n" + "".join(f"{key:X};{' '.join(f'{x:X}' for x in value)}\n" for key, value in mappings.items())).encode("ascii"))
    metadata = dict(unicodeVersion="17.0.0", sources={name: dict(url=BASE + name, sha256=hashlib.sha256(payload).hexdigest()) for name, payload in sources.items()}, changedScalars=len(mappings), simpleMappings=len(simple), expansions=len(expansions), maximumEmittedUtf16UnitsPerScalar=3, language="Default Unicode only; conditional and language-tailored casing is separate unfinished work.")
    (bank / "unicode-data.json").write_bytes((json.dumps(metadata, indent=2) + "\n").encode("utf-8"))
    print(json.dumps(metadata))


if __name__ == "__main__":
    main()
